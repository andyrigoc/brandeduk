const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(projectRoot, 'home-pc.html');
const outputPath = path.join(
    projectRoot,
    'brandedukv15-child',
    'assets',
    'js',
    'pc-header-template.js'
);

const source = fs.readFileSync(sourcePath, 'utf8');
const headerMatch = source.match(/<header class="site-header">[\s\S]*?<\/header>/);
const promoMatch = source.match(/<div class="top-promo-bar">[\s\S]*?<\/div>\s*<\/div>/);
const overlayMatch = source.match(/<div class="popup-overlay" id="popupOverlay"><\/div>/);
const contactMatch = source.match(/<div class="popup-contact" id="popupContact">[\s\S]*?\r?\n<\/div>/);

if (!headerMatch || !promoMatch) {
    throw new Error('Unable to find the canonical PC header or promotional bar in home-pc.html.');
}
if (!overlayMatch || !contactMatch) {
    throw new Error('Unable to find the canonical contact popup in home-pc.html.');
}

const template = `${headerMatch[0]}\n${promoMatch[0]}`;
const contactTemplate = `${overlayMatch[0]}\n${contactMatch[0]}`;
const generated = [
    '/* Generated from home-pc.html by maintenance/build-pc-header-template.js. */',
    '/* Do not edit this file directly; update home-pc.html and run the generator. */',
    `window.BrandedPcHeaderTemplate = ${JSON.stringify(template)};`,
    `window.BrandedPcContactTemplate = ${JSON.stringify(contactTemplate)};`,
    ''
].join('\n');

fs.writeFileSync(outputPath, generated, 'utf8');
console.log(`PC_HEADER_TEMPLATE_BUILT ${path.relative(projectRoot, outputPath)}`);

